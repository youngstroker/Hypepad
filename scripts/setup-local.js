// Writes a .env for local development:
//   Solana devnet  + a local Hardhat chain standing in for HyperEVM.
// It generates a fresh devnet treasury keypair (devnet SOL has no value) and
// uses Hardhat's well-known test account #1 as the relayer. Never reuse any of
// these keys anywhere real.
import fs from 'node:fs';
import path from 'node:path';
import bs58 from 'bs58';
import { Keypair } from '@solana/web3.js';

const root = path.resolve(import.meta.dirname, '..');
const envPath = path.join(root, '.env');
if (fs.existsSync(envPath) && !process.argv.includes('--force')) {
    console.error('.env already exists. Re-run with --force to overwrite it.');
    process.exit(1);
}
const deployment = JSON.parse(fs.readFileSync(path.join(root, 'contracts/deployments/localhost.json'), 'utf8'));
const treasury = Keypair.generate();

const env = `# Generated by npm run setup:local — LOCAL DEVELOPMENT ONLY
PORT=4191
PUBLIC_URL=http://127.0.0.1:4191
SITE_NAME=HyperPump

SOLANA_CLUSTER=devnet
TREASURY_PUBLIC_KEY=${treasury.publicKey.toBase58()}
TREASURY_SECRET_KEY=${bs58.encode(treasury.secretKey)}

HYPEREVM_CHAIN_ID=31337
HYPEREVM_RPC_URL=http://127.0.0.1:8545
HYPEREVM_EXPLORER=
FACTORY_ADDRESS=${deployment.factory}
FACTORY_DEPLOY_BLOCK=${deployment.deployBlock}
# Hardhat test account #1 (public, well-known key)
RELAYER_PRIVATE_KEY=0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d

# Local chain: real prices still come from Hyperliquid/CoinGecko unless you pin them.
# PRICE_FIXED_SOL_USD=150
# PRICE_FIXED_HYPE_USD=30
LAUNCH_FEE_SOL=0.02
`;
fs.writeFileSync(envPath, env, { mode: 0o600 });
console.log(`Wrote .env\nDevnet treasury: ${treasury.publicKey.toBase58()}`);
